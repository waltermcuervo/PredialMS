CREATE USER TOL IDENTIFIED BY "admin123";
ALTER USER TOL QUOTA UNLIMITED ON USERS;
GRANT CONNECT, RESOURCE TO TOL;
GRANT CREATE PROCEDURE TO TOL;

CREATE TABLE TOL.CONTRIBUYENTE (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TIPO_DOCUMENTO VARCHAR(5) NOT NULL,
    NUM_DOCUMENTO VARCHAR2(50) NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    APELLIDO VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(150),
    TELEFONO VARCHAR2(20),
    FECHA_REGISTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UQ_NUM_DOCUMENTO UNIQUE (NUM_DOCUMENTO)
);

CREATE INDEX IDX_NUM_DOCUMENTO ON TOL.CONTRIBUYENTE (NUM_DOCUMENTO);

COMMENT ON COLUMN TOL.CONTRIBUYENTE.ID IS 'Identificador unico de la entidad';
COMMENT ON COLUMN TOL.CONTRIBUYENTE.TIPO_DOCUMENTO IS 'Tipo de documento del contribuyente';
COMMENT ON COLUMN TOL.CONTRIBUYENTE.NUM_DOCUMENTO IS 'numero de documento del contribuyente';
COMMENT ON COLUMN TOL.CONTRIBUYENTE.MOMBRE IS 'nombre del contribuyente';
COMMENT ON COLUMN TOL.CONTRIBUYENTE.APELLIDO IS 'Apellido del contribuyente';
COMMENT ON COLUMN TOL.CONTRIBUYENTE.EMAIL IS 'correo electronico del contribuyente';
COMMENT ON COLUMN TOL.CONTRIBUYENTE.TELEFONO IS 'numero de telefono del contribunyente';
COMMENT ON COLUMN TOL.CONTRIBUYENTE.FECHA_REGISTRO IS 'fecha en que el contribuyente se registro en el sistema';


CREATE TABLE TOL.CUENTA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COD_CATASTRAL VARCHAR2(100) NOT NULL,
    CONTRIBUYENTE_ID NUMBER(19) NOT NULL,
    DEUDA_VALOR NUMBER(15,2) DEFAULT 0.0 NOT NULL,
    ESTADO VARCHAR2(10) NOT NULL,
    FECHA_VENCIMIENTO DATE,
    CONSTRAINT FK_CUENTA_CONTRIBUYENTE FOREIGN KEY (CONTRIBUYENTE_ID) REFERENCES TOL.CONTRIBUYENTE(ID),
    CONSTRAINT CHK_ESTADO CHECK (ESTADO IN ('AL_DIA', 'EN_MORA'))
);
CREATE INDEX IDX_COD_CATASTRAL ON TOL.CUENTA (COD_CATASTRAL);
CREATE INDEX IDX_COD_CATASTRAL_CONTRIBUYENTE ON TOL.CUENTA (COD_CATASTRAL, CONTRIBUYENTE_ID);

COMMENT ON COLUMN TOL.CUENTA.ID IS 'identificador de la entidad';
COMMENT ON COLUMN TOL.CUENTA.COD_CATASTRAL IS 'codigo del catastro';
COMMENT ON COLUMN TOL.CUENTA.CONTRIBUYENTE_ID IS 'identificador del contribuyente';
COMMENT ON COLUMN TOL.CUENTA.DEUDA_VALOR IS 'deuda del contribuyente';
COMMENT ON COLUMN TOL.CUENTA.ESTADO IS 'estado de la cuenta, puede ser (AL_DIA, EN_MORA)';
COMMENT ON COLUMN TOL.CUENTA.FECHA_VENCIMIENTO IS 'fecha de vencimineto de la deuda para definir el estado';
